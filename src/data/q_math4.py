def _grid(cols, rows, marks):
    """최단 경로 문제용 바둑판 길. marks: [(x, y, 글자)]"""
    p = Plot(0, cols, 0, rows, w=40 * cols + 50, h=40 * rows + 50, pad=25, axes=False)
    for i in range(cols + 1):
        p.seg(i, 0, i, rows, width=1.6)
    for j in range(rows + 1):
        p.seg(0, j, cols, j, width=1.6)
    for x, y, s in marks:
        p.dot(x, y, s, dx=-14 if x == 0 else 6, dy=16 if y == 0 else -6)
    return p


