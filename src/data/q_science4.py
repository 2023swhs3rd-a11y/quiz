def _vt(lines, tmax, vmax, ticks_t, ticks_v, xlabel="t(s)", ylabel="v(m/s)", labels=()):
    p = Plot(-0.3, tmax + 0.6, -0.3 * vmax / 5, vmax * 1.15, xlabel=xlabel, ylabel=ylabel)
    for pts in lines:
        for (x1, y1), (x2, y2) in zip(pts, pts[1:]):
            p.seg(x1, y1, x2, y2, width=2)
    for t in ticks_t:
        p.tick(x=t)
    for v in ticks_v:
        p.tick(y=v)
    for x, y, s in labels:
        p.text(x, y, s, dx=4, dy=-6)
    return p


