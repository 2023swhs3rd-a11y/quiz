def B(*lines):
    return "<div class='box'>" + "<br>".join(lines) + "</div>"


def T(events, caption="연표"):
    """연표: events = [(연도, 사건)] 6개 → 사이 구간 (가)~(마)"""
    n = len(events)
    w, h, pad = 330, 132, 24
    step = (w - 2 * pad) / (n - 1)
    y = 52
    out = [f"<line x1='{pad - 6}' y1='{y}' x2='{w - pad + 6}' y2='{y}' stroke='currentColor' stroke-width='1.6'/>"]
    for i, (yr, ev) in enumerate(events):
        x = pad + i * step
        out.append(f"<circle cx='{x:.1f}' cy='{y}' r='3.5' fill='currentColor'/>")
        out.append(f"<text x='{x:.1f}' y='{y - 10}' font-size='11' text-anchor='middle' fill='currentColor' font-weight='700'>{yr}</text>")
        for j, part in enumerate(ev.split("|")):
            out.append(f"<text x='{x:.1f}' y='{y + 18 + j * 13}' font-size='10.5' text-anchor='middle' fill='currentColor'>{part}</text>")
    for i in range(n - 1):
        x = pad + (i + 0.5) * step
        out.append(f"<text x='{x:.1f}' y='{y - 30}' font-size='12' text-anchor='middle' fill='currentColor'>{ABCDE[i]}</text>")
    return (f"<figure class='fig'><svg viewBox='0 0 {w} {h}' width='{w}' height='{h}' role='img' aria-label='{caption}'>"
            + "".join(out) + f"</svg><figcaption>{caption}</figcaption></figure>")


