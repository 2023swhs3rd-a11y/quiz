def _fig_bisect():
    p = Plot(-0.5, 4.8, -0.6, 4.6, w=260, h=220)
    p.curve(lambda x: -x * x + 4 * x, 0, 4)
    m = 4 - 32 ** (1 / 3)
    p.shade(lambda x: -x * x + 4 * x, lambda x: m * x, 0, 4 - m)
    p.seg(0, 0, 4.5, 4.5 * m, width=1.6).text(4.5, 4.5 * m, "y = mx", dx=-44, dy=-8, size=12)
    p.dot(4, 0, "4", dx=-4, dy=16)
    return p.svg("곡선 y = −x² + 4x와 직선 y = mx")


def _fig_tangent_cubic():
    p = Plot(-2.6, 2, -9, 4, w=260, h=240)
    p.curve(lambda x: x ** 3, -2.1, 1.6)
    p.curve(lambda x: 3 * x - 2, -2.4, 1.9)
    p.shade(lambda x: x ** 3, lambda x: 3 * x - 2, -2, 1)
    p.dot(1, 1, "(1, 1)", dx=8, dy=4)
    p.text(1.5, 3.4, "y = x³", dx=-50, dy=0, size=12)
    return p.svg("곡선 y = x³과 점 (1, 1)에서의 접선")


def _fig_lattice_sin():
    p = Plot(-1, 9.5, -1.5, 1.6, w=300, h=180)
    p.curve(lambda x: __import__("math").sin(__import__("math").pi * x / 2), -0.5, 9.2)
    p.seg(-0.5, -0.5 / 8, 9.2, 9.2 / 8, dash=True, width=1.2)
    for x in (2, 4, 6, 8):
        p.tick(x=x, label=str(x))
    p.tick(y=1, label="1")
    return p.svg("y = sin(πx/2)과 y = x/8 (x ≥ 0 부분)")


