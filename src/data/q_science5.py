_used = collections.Counter()


def KQ(q, truth, e, p):
    """truth: 옳은 보기(예: 'ㄱㄷ'). 정답이 들어 있는 선택지 묶음 가운데, 지금까지 가장 적게 쓴 정답 위치가 되는 것을 고른다."""
    want = ", ".join(truth)
    best = None
    for pat in _PATTERNS:
        if want in pat:
            pos = pat.index(want) + 1
            if best is None or _used[pos] < _used[best[1]]:
                best = (pat, pos)
    _used[best[1]] += 1
    return Q("수능", 3, "최상", q, list(best[0]), best[1], e, p)


